export const locales = ["en", "ru"] as const;
export type Locale = (typeof locales)[number];

export function getLocale(value: string | null | undefined): Locale {
  return value === "ru" ? "ru" : "en";
}

export function withLocale(pathname: string, locale: Locale, params: Record<string, string> = {}): string {
  const search = new URLSearchParams({ ...params, lang: locale });
  return `${pathname}?${search.toString()}`;
}

